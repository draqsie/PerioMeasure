package com.periomeasure.session;

/** Optional landmark groups the user can switch on per session. */
public enum OptionalLandmark {
    /** Upper lid crease (TPS). */
    CREASE,
    /** Lower brow border (brow height). */
    BROW,
    /** Upper and lower limbus (scleral show). */
    LIMBUS,
    /** Fissure contour polygon (area). */
    CONTOUR
}
